-- ============================================================
-- Call diagnostics: an append-only signal/ICE trace, plus a
-- database guard that stops an answered consultation from being
-- re-labelled as missed.
-- ============================================================
-- Two problems this closes.
--
-- 1) Attribution. 21 calls are recorded and 13 are 'missed', but a 'missed' row
-- cannot tell "the invite never reached the callee" from "the callee accepted and
-- the SDP offer never arrived". The client logs to console only, so the evidence
-- dies with the tab. call_events keeps the trace per call so the next sweep of
-- calls can be attributed instead of argued about.
--
-- 2) Status downgrade. Both participants write their own observed transition, and
-- the client UPDATEs were guarded only on ended_at IS NULL. A peer that never saw
-- the connection reach 'connected' therefore overwrote 'answered' with 'missed'
-- (real row: answered_at set and duration_seconds 39, status 'missed'). The client
-- guards get the same fix, and this trigger makes the rule impossible to bypass.

-- ------------------------------------------------------------
-- 1. call_events
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.call_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id uuid NOT NULL,
  user_id uuid NOT NULL,
  event text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT call_events_event_shape CHECK (
    char_length(event) BETWEEN 1 AND 40 AND event ~ '^[a-z][a-z0-9_]*$'
  ),
  CONSTRAINT call_events_detail_object CHECK (jsonb_typeof(detail) = 'object')
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.call_events'::regclass AND conname = 'call_events_call_id_fkey'
  ) THEN
    ALTER TABLE public.call_events
      ADD CONSTRAINT call_events_call_id_fkey FOREIGN KEY (call_id)
      REFERENCES public.calls (id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.call_events'::regclass AND conname = 'call_events_user_id_fkey'
  ) THEN
    ALTER TABLE public.call_events
      ADD CONSTRAINT call_events_user_id_fkey FOREIGN KEY (user_id)
      REFERENCES public.users (id) ON DELETE CASCADE;
  END IF;
END $$;

-- The diagnosis reads one call's trace in order, and scans recent failures by event.
CREATE INDEX IF NOT EXISTS call_events_call_idx
  ON public.call_events (call_id, id);
CREATE INDEX IF NOT EXISTS call_events_recent_idx
  ON public.call_events (event, created_at DESC);

ALTER TABLE public.call_events ENABLE ROW LEVEL SECURITY;

-- public-schema default privileges hand anon and authenticated ALL on a new table,
-- and RLS does not narrow table privileges, so revoke by name.
REVOKE ALL ON TABLE public.call_events FROM anon;
REVOKE ALL ON TABLE public.call_events FROM authenticated;
GRANT INSERT, SELECT ON TABLE public.call_events TO authenticated;
GRANT ALL ON TABLE public.call_events TO service_role;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'call_events' AND policyname = 'call_events_insert_participant'
  ) THEN
    -- A device may only log its own trace, and only onto a call it is a participant of.
    CREATE POLICY "call_events_insert_participant" ON public.call_events
      FOR INSERT TO authenticated
      WITH CHECK (
        auth.uid() = user_id
        AND EXISTS (
          SELECT 1 FROM public.calls c
          WHERE c.id = call_events.call_id
            AND auth.uid() IN (c.caller_id, c.callee_id)
        )
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'call_events' AND policyname = 'call_events_select_participant'
  ) THEN
    CREATE POLICY "call_events_select_participant" ON public.call_events
      FOR SELECT TO authenticated
      USING (EXISTS (
        SELECT 1 FROM public.calls c
        WHERE c.id = call_events.call_id
          AND auth.uid() IN (c.caller_id, c.callee_id)
      ));
  END IF;
  -- No UPDATE or DELETE policy: the trace stays append-only, and the foreign key to
  -- calls means removing a consultation record removes its diagnostics with it.
END $$;

-- Diagnostics are not consultation metadata: they pile up per state change, so they
-- age out instead of outliving their debugging value.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    IF EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'call events prune') THEN
      PERFORM cron.unschedule('call events prune');
    END IF;
    PERFORM cron.schedule(
      'call events prune',
      '45 3 * * *',
      $CRON$ DELETE FROM public.call_events WHERE created_at < now() - interval '14 days' $CRON$
    );
  ELSE
    RAISE NOTICE 'pg_cron is not installed; call diagnostics will not be pruned.';
  END IF;
END $$;

-- ------------------------------------------------------------
-- 2. Status downgrade guard on calls
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.calls_block_status_downgrade()
RETURNS trigger AS $$
BEGIN
  -- Once a call is on the record as answered, only forward transitions survive:
  -- a peer that missed the 'connected' transition may not rewrite it as unanswered.
  IF NEW.status IS DISTINCT FROM OLD.status
    AND OLD.answered_at IS NOT NULL
    AND NEW.status IN ('ringing', 'missed', 'declined') THEN
    NEW := OLD;
    RETURN NEW;
  END IF;

  -- A closed call stays closed.
  IF NEW.status IS DISTINCT FROM OLD.status
    AND OLD.status = 'ended'
    AND NEW.status <> 'ended' THEN
    NEW := OLD;
    RETURN NEW;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public, pg_temp;

DROP TRIGGER IF EXISTS calls_block_status_downgrade ON public.calls;
CREATE TRIGGER calls_block_status_downgrade
  BEFORE UPDATE ON public.calls
  FOR EACH ROW EXECUTE FUNCTION public.calls_block_status_downgrade();
